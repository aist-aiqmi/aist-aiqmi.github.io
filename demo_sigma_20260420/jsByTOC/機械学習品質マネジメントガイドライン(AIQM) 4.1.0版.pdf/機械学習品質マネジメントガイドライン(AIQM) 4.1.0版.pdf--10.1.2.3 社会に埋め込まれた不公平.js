持つ属性値については、たとえ正しく同定できたとしても、どのような扱いをすべきかは自
明ではない。例えば貸し出しの与信業務のような事例において、「返済可能額」は測定不能
だが推定したい属性であると考えられる。このとき、性別のような明確に「差別すべきでな
い」属性や、あるいは「貸出額」のような目的関数に明確に入力として特定できる変数の場
合には、それぞれ扱い方の方向性は自明である。一方で例えば「収入額」のような属性は、
