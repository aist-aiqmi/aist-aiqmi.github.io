の特徴などが要配慮属性と隠れた相関を持ち、結果的に差別を統計的に再現してしまうこ
とがある。例えば、氏名と性別とか、学歴の学校名と性別、住所と収入額のような属性間の
相関関係や、画像の背景と人の性格・性別などの、要配慮属性と相関する情報が訓練元デー
タに含まれていると、要配慮属性の出力への直接的な寄与を削除しても、結果的に公平でな
い出力が生み出されることが有り得る。 
