（2）成果物は何か
　従来のAI開発では、成果物の中心は「学習済みモデル」であったが、生成AIの開発の場合、モデルの権利
は生成AIの提供事業者が有しているため、成果物には含まれないのが通常であり、成果物について明確
にしておく必要がある。
