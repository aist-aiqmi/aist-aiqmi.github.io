利用することから、ユーザから提供されたデータは、当然ながら生成AIサービス提供者が提供する生成
AIサービスに入力されるという前提で提供される。
　その場合、情報管理の観点から、ユーザとしては、以下の事項を含む契約をベンダと生成AIサービス
提供者との間で締結したうえで生成AIサービスを利用することをベンダに義務付けることが必要な場合
が多い（なお、生成AIサービスの利用契約をベンダではなくユーザが締結することもあり、その場合には、
かかる条項は不要である。）。
